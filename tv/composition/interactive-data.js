function card(kind, item) {
  const element = document.createElement("div");
  element.className = `${kind} reveal interactive-card`;
  const visibleTitle = kind === "myth" ? item[0].charAt(0).toUpperCase() + item[0].slice(1) : item[0];
  element.textContent = visibleTitle;
  element.dataset.title = visibleTitle;
  element.dataset.detail = item[1];
  if (kind === "rubric") element.dataset.sourceLabel = item[2];
  if (kind === "myth") {
    const source = SOURCES[item[2]];
    element.dataset.sourceLabel = source[0];
    element.dataset.sourceUrl = source[1];
  }
  return element;
}

TOPICS.forEach((item) => document.querySelector("#topic-wall").append(card("topic-chip", item)));
