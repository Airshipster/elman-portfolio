const detailPanel = document.querySelector("#detail-panel");
const detailTitle = detailPanel.querySelector("h3");
const detailText = detailPanel.querySelector("p");
const detailSource = detailPanel.querySelector("a");
let lockedCard = null;

function openDetail(element) {
  detailTitle.textContent = element.dataset.title;
  detailText.textContent = element.dataset.detail;
  detailSource.textContent = element.dataset.sourceLabel || "Почему это важно";
  if (element.dataset.sourceUrl) {
    detailSource.href = element.dataset.sourceUrl;
    detailSource.style.display = "inline";
  } else {
    detailSource.removeAttribute("href");
    detailSource.style.display = element.dataset.sourceLabel ? "inline" : "none";
  }
  detailPanel.classList.add("is-open");
  gsap.to(detailPanel, { opacity: 1, visibility: "visible", y: 0, scale: 1, duration: .24, ease: "power2.out", overwrite: true });
}

function closeDetail(force = false) {
  if (lockedCard && !force) return;
  gsap.to(detailPanel, { opacity: 0, y: 18, scale: .97, duration: .18, ease: "power2.in", overwrite: true, onComplete: () => detailPanel.classList.remove("is-open") });
}

document.addEventListener("deck-language-change", () => {
  const card = lockedCard || document.querySelector(".interactive-card:hover");
  if (card && detailPanel.classList.contains("is-open")) openDetail(card);
});

document.querySelectorAll(".interactive-card").forEach((element) => {
  element.addEventListener("mouseenter", () => { if (!lockedCard) openDetail(element); });
  element.addEventListener("mouseleave", () => closeDetail());
  element.addEventListener("click", (event) => {
    event.stopPropagation();
    document.querySelectorAll(".interactive-card.is-selected").forEach((item) => item.classList.remove("is-selected"));
    lockedCard = lockedCard === element ? null : element;
    if (lockedCard) {
      element.classList.add("is-selected");
      openDetail(element);
    } else closeDetail(true);
  });
});

document.querySelector("#detail-close").addEventListener("click", () => {
  if (lockedCard) lockedCard.classList.remove("is-selected");
  lockedCard = null;
  closeDetail(true);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    if (lockedCard) lockedCard.classList.remove("is-selected");
    lockedCard = null;
    closeDetail(true);
  }
});

document.addEventListener("click", (event) => {
  if (!detailPanel.contains(event.target) && !event.target.closest(".interactive-card")) {
    if (lockedCard) lockedCard.classList.remove("is-selected");
    lockedCard = null;
    closeDetail(true);
  }
});
